// Command context-summarization-google summarizes the conversation as it grows:
// Google Gemini.
//
// It enables automatic context summarization, which compresses the
// conversation history when token limits are approached, and shows that
// summarization handles function calls correctly, preserving incomplete
// function call sequences.
//
//	DEEPGRAM_API_KEY=… CARTESIA_API_KEY=… GOOGLE_API_KEY=… \
//	  go run ./examples/context-summarization/context-summarization-google
//
// Then open http://localhost:7860 and connect.
package main


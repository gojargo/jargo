// Command realtime-rime is a voice agent on Rime's Prism, a speech-to-speech
// model: it hears the caller, speaks its answers, and calls tools, with turn
// detection done server-side.
//
//	RIME_API_KEY=… go run ./examples/realtime/realtime-rime
//
// RIME_REALTIME_ENDPOINT, when set, overrides the Prism endpoint.
//
// Then open http://localhost:7860 and connect.

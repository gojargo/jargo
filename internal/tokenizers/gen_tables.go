//go:build ignore

// gen_tables writes tables.go: the Unicode data Hugging Face tokenizers 0.23.3
// encodes with, read from the sources of the Rust crates it links. Those crates
// pin older Unicode versions than Go's unicode package, so the tables are taken
// from them rather than from Go:
//
//	unicode-normalization-alignments 0.1.12 (Unicode 9.0.0): src/tables.rs
//	unicode_categories 0.1.1: src/tables.rs
//	onig_sys 69.9.3 (Oniguruma 6.9.10, Unicode 16.0): oniguruma/src/unicode_property_data.c
//
// Usage, with each crate unpacked from crates.io:
//
//	go run gen_tables.go <unicode-normalization-alignments dir> <unicode_categories dir> <onig_sys dir>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

type runeRange struct{ lo, hi uint32 }

func main() {
	if len(os.Args) != 4 {
		log.Fatal("usage: go run gen_tables.go <unicode-normalization-alignments> <unicode_categories> <onig_sys>")
	}
	norm := read(filepath.Join(os.Args[1], "src", "tables.rs"))
	cats := read(filepath.Join(os.Args[2], "src", "tables.rs"))
	onig := read(filepath.Join(os.Args[3], "oniguruma", "src", "unicode_property_data.c"))

	if !strings.Contains(norm, "pub const UNICODE_VERSION: (u64, u64, u64) = (9, 0, 0);") {
		log.Fatal("unexpected unicode-normalization-alignments Unicode version")
	}
	if !strings.Contains(onig, "#define UNICODE_PROPERTY_VERSION  160000") {
		log.Fatal("unexpected Oniguruma Unicode version")
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_tables.go; DO NOT EDIT.\n\n")
	b.WriteString("package tokenizers\n\nimport \"unicode\"\n\n")

	// unicode_categories: is_other (Cc, Cf and Co; the crate leaves Cn out),
	// is_punctuation and is_mark_nonspacing. Its tables list single code
	// points, and is_other_private_use adds three ranges in code.
	other := charList(cats, "OTHER_CONTROL")
	other = append(other, charList(cats, "OTHER_FORMAT")...)
	other = append(other, charList(cats, "OTHER_PRIVATE_USE")...)
	otherRanges := append(toRanges(other), runeRange{0xE000, 0xF8FF}, runeRange{0xF0000, 0xFFFFD}, runeRange{0x100000, 0x10FFFD})
	var punct []uint32
	for _, name := range []string{
		"PUNCTUATION_CONNECTOR", "PUNCTUATION_DASH", "PUNCTUATION_CLOSE", "PUNCTUATION_FINAL_QUOTE",
		"PUNCTUATION_INITIAL_QUOTE", "PUNCTUATION_OTHER", "PUNCTUATION_OPEN",
	} {
		punct = append(punct, charList(cats, name)...)
	}
	writeTable(&b, "categoryOther", "the code points unicode_categories 0.1.1 reports as is_other.", otherRanges)
	writeTable(&b, "categoryPunctuation", "the code points unicode_categories 0.1.1 reports as is_punctuation.", toRanges(punct))
	writeTable(&b, "categoryMarkNonspacing", "the code points unicode_categories 0.1.1 reports as is_mark_nonspacing.", toRanges(charList(cats, "MARK_NONSPACING")))

	// Oniguruma: \p{L}, \p{N} and \s.
	writeTable(&b, "onigLetter", "Oniguruma's \\p{L} (Unicode 16.0).", onigRanges(onig, "CR_L"))
	writeTable(&b, "onigNumber", "Oniguruma's \\p{N} (Unicode 16.0).", onigRanges(onig, "CR_N"))
	writeTable(&b, "onigSpace", "Oniguruma's \\s for UTF-8 (the White_Space property).", onigRanges(onig, "CR_Space"))

	// unicode-normalization-alignments: combining classes, full canonical
	// decompositions and the canonical composition pairs.
	ccc := u32List(norm, "CANONICAL_COMBINING_CLASS")
	cccPairs := make([][2]uint32, 0, len(ccc))
	for _, kv := range ccc {
		cccPairs = append(cccPairs, [2]uint32{kv >> 8, kv & 0xff})
	}
	slices.SortFunc(cccPairs, func(a, b [2]uint32) int { return int(a[0]) - int(b[0]) })
	b.WriteString("// combiningClass holds code<<8 | class for every code point with a non-zero\n")
	b.WriteString("// canonical combining class (Unicode 9.0.0), sorted.\n")
	b.WriteString("var combiningClass = [...]uint32{\n")
	for _, p := range cccPairs {
		if p[1] != 0 {
			fmt.Fprintf(&b, "0x%X,\n", p[0]<<8|p[1])
		}
	}
	b.WriteString("}\n\n")

	decomp := decompositions(norm)
	b.WriteString("// canonicalDecomposition maps a code point to its full canonical decomposition\n")
	b.WriteString("// (Unicode 9.0.0), as start<<4 | length in decompositionData. Hangul\n")
	b.WriteString("// syllables are decomposed in code.\n")
	b.WriteString("var canonicalDecomposition = map[rune]uint32{\n")
	keys := make([]uint32, 0, len(decomp))
	for k := range decomp {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var data []uint32
	for _, k := range keys {
		d := decomp[k]
		if len(d) >= 16 {
			log.Fatalf("decomposition of %X too long", k)
		}
		fmt.Fprintf(&b, "0x%X: 0x%X,\n", k, uint32(len(data))<<4|uint32(len(d)))
		data = append(data, d...)
	}
	b.WriteString("}\n\n")
	b.WriteString("// decompositionData holds the decompositions canonicalDecomposition points at.\n")
	b.WriteString("var decompositionData = [...]rune{\n")
	for i, r := range data {
		fmt.Fprintf(&b, "0x%X,", r)
		if i%8 == 7 {
			b.WriteString("\n")
		}
	}
	b.WriteString("\n}\n\n")

	comp := compositions(norm)
	b.WriteString("// canonicalComposition maps first<<21 | second to the primary composite\n")
	b.WriteString("// (Unicode 9.0.0). Hangul syllables are composed in code.\n")
	b.WriteString("var canonicalComposition = map[uint64]rune{\n")
	ckeys := make([]uint64, 0, len(comp))
	for k := range comp {
		ckeys = append(ckeys, k)
	}
	slices.Sort(ckeys)
	for _, k := range ckeys {
		fmt.Fprintf(&b, "0x%X: 0x%X,\n", k, comp[k])
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	return string(b)
}

var charRe = regexp.MustCompile(`'\\u\{([0-9A-Fa-f]+)\}'`)

// block returns the text between the declaration of name and the closing "];".
func block(src, decl string) string {
	i := strings.Index(src, decl)
	if i < 0 {
		log.Fatalf("%s not found", decl)
	}
	j := strings.Index(src[i:], "];")
	if j < 0 {
		log.Fatalf("%s not terminated", decl)
	}
	return src[i : i+j]
}

func charList(src, name string) []uint32 {
	var out []uint32
	for _, m := range charRe.FindAllStringSubmatch(block(src, "pub static "+name+" "), -1) {
		out = append(out, hex(m[1]))
	}
	if len(out) == 0 {
		log.Fatalf("%s is empty", name)
	}
	return out
}

var u32Re = regexp.MustCompile(`0x([0-9A-Fa-f]+)`)

// u32List reads a perfect-hash key/value table and checks every entry is
// reachable through the crate's lookup, so the set read is the set it serves.
func u32List(src, name string) []uint32 {
	salt := saltList(src, name)
	var out []uint32
	for _, m := range u32Re.FindAllStringSubmatch(block(src, name+"_KV: &[u32] = &["), -1) {
		out = append(out, hex(m[1]))
	}
	if len(out) != len(salt) {
		log.Fatalf("%s: %d entries for %d salts", name, len(out), len(salt))
	}
	for i, kv := range out {
		if mph(kv>>8, salt) != i {
			log.Fatalf("%s: entry %d unreachable", name, i)
		}
	}
	return out
}

func saltList(src, name string) []uint32 {
	var out []uint32
	body := block(src, name+"_SALT: &[u16] = &[")
	body = body[strings.Index(body, "= &[")+4:]
	for _, f := range strings.FieldsFunc(body, func(r rune) bool { return r == ',' || r == ' ' || r == '\n' }) {
		v, err := strconv.ParseUint(strings.TrimPrefix(f, "0x"), 16, 32)
		if err != nil {
			log.Fatalf("%s salt %q: %v", name, f, err)
		}
		out = append(out, uint32(v))
	}
	return out
}

func myHash(key, salt uint32, n int) int {
	y := (key + salt) * 2654435769
	y ^= key * 0x31415926
	return int((uint64(y) * uint64(n)) >> 32)
}

func mph(key uint32, salt []uint32) int {
	s := salt[myHash(key, 0, len(salt))]
	return myHash(key, s, len(salt))
}

var pairRe = regexp.MustCompile(`\(0x([0-9A-Fa-f]+), '\\u\{([0-9A-Fa-f]+)\}'\)`)

func compositions(src string) map[uint64]uint32 {
	salt := saltList(src, "COMPOSITION_TABLE")
	out := map[uint64]uint32{}
	ms := pairRe.FindAllStringSubmatch(block(src, "COMPOSITION_TABLE_KV: &[(u32, char)] = &["), -1)
	if len(ms) != len(salt) {
		log.Fatalf("composition: %d entries for %d salts", len(ms), len(salt))
	}
	for i, m := range ms {
		key := hex(m[1])
		if mph(key, salt) != i {
			log.Fatalf("composition: entry %d unreachable", i)
		}
		out[uint64(key>>16)<<21|uint64(key&0xffff)] = hex(m[2])
	}
	astral := src[strings.Index(src, "pub(crate) fn composition_table_astral"):]
	astral = astral[:strings.Index(astral, "_ => None")]
	arm := regexp.MustCompile(`\('\\u\{([0-9A-Fa-f]+)\}', '\\u\{([0-9A-Fa-f]+)\}'\) => Some\('\\u\{([0-9A-Fa-f]+)\}'\)`)
	n := 0
	for _, m := range arm.FindAllStringSubmatch(astral, -1) {
		out[uint64(hex(m[1]))<<21|uint64(hex(m[2]))] = hex(m[3])
		n++
	}
	if n == 0 {
		log.Fatal("no astral compositions")
	}
	return out
}

var decompRe = regexp.MustCompile(`\(0x([0-9A-Fa-f]+), &\[([^\]]*)\]\)`)

func decompositions(src string) map[uint32][]uint32 {
	salt := saltList(src, "CANONICAL_DECOMPOSED")
	out := map[uint32][]uint32{}
	ms := decompRe.FindAllStringSubmatch(block(src, "CANONICAL_DECOMPOSED_KV: &[(u32, &'static [char])] = &["), -1)
	if len(ms) != len(salt) {
		log.Fatalf("decomposition: %d entries for %d salts", len(ms), len(salt))
	}
	for i, m := range ms {
		key := hex(m[1])
		if mph(key, salt) != i {
			log.Fatalf("decomposition: entry %d unreachable", i)
		}
		var rs []uint32
		for _, c := range charRe.FindAllStringSubmatch(m[2], -1) {
			rs = append(rs, hex(c[1]))
		}
		out[key] = rs
	}
	return out
}

func onigRanges(src, name string) []runeRange {
	i := strings.Index(src, "\n"+name+"[] = {")
	if i < 0 {
		log.Fatalf("%s not found", name)
	}
	body := src[i:]
	body = body[strings.Index(body, "{")+1 : strings.Index(body, "}")]
	fields := strings.FieldsFunc(body, func(r rune) bool { return r == ',' || r == ' ' || r == '\n' })
	n, err := strconv.Atoi(fields[0])
	if err != nil || len(fields) != 1+2*n {
		log.Fatalf("%s: bad table", name)
	}
	var out []runeRange
	for k := 0; k < n; k++ {
		out = append(out, runeRange{hex(strings.TrimPrefix(fields[1+2*k], "0x")), hex(strings.TrimPrefix(fields[2+2*k], "0x"))})
	}
	return out
}

func hex(s string) uint32 {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return uint32(v)
}

func toRanges(cps []uint32) []runeRange {
	cps = slices.Clone(cps)
	slices.Sort(cps)
	cps = slices.Compact(cps)
	var out []runeRange
	for _, c := range cps {
		if len(out) > 0 && out[len(out)-1].hi+1 == c {
			out[len(out)-1].hi = c
			continue
		}
		out = append(out, runeRange{c, c})
	}
	return out
}

// merge sorts and coalesces overlapping or adjacent ranges.
func merge(rs []runeRange) []runeRange {
	rs = slices.Clone(rs)
	slices.SortFunc(rs, func(a, b runeRange) int { return int(a.lo) - int(b.lo) })
	var out []runeRange
	for _, r := range rs {
		if len(out) > 0 && r.lo <= out[len(out)-1].hi+1 {
			out[len(out)-1].hi = max(out[len(out)-1].hi, r.hi)
			continue
		}
		out = append(out, r)
	}
	return out
}

func writeTable(b *bytes.Buffer, name, doc string, rs []runeRange) {
	rs = merge(rs)
	fmt.Fprintf(b, "// %s holds %s\n", name, doc)
	fmt.Fprintf(b, "var %s = &unicode.RangeTable{\n", name)
	var r16, r32 []runeRange
	for _, r := range rs {
		switch {
		case r.hi <= 0xFFFF:
			r16 = append(r16, r)
		case r.lo > 0xFFFF:
			r32 = append(r32, r)
		default:
			r16 = append(r16, runeRange{r.lo, 0xFFFF})
			r32 = append(r32, runeRange{0x10000, r.hi})
		}
	}
	latin := 0
	if len(r16) > 0 {
		b.WriteString("R16: []unicode.Range16{\n")
		for _, r := range r16 {
			fmt.Fprintf(b, "{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", r.lo, r.hi)
			if r.hi <= 0xFF {
				latin++
			}
		}
		b.WriteString("},\n")
	}
	if len(r32) > 0 {
		b.WriteString("R32: []unicode.Range32{\n")
		for _, r := range r32 {
			fmt.Fprintf(b, "{Lo: 0x%X, Hi: 0x%X, Stride: 1},\n", r.lo, r.hi)
		}
		b.WriteString("},\n")
	}
	if latin > 0 {
		fmt.Fprintf(b, "LatinOffset: %d,\n", latin)
	}
	b.WriteString("}\n\n")
}
